create or replace function public.ensure_rorisk_race()
returns public.rorisk_races
language plpgsql
security definer
set search_path = public
as $$
declare
  v_race public.rorisk_races%rowtype;
  v_expired public.rorisk_races%rowtype;
begin
  select * into v_race
  from public.rorisk_races
  where status = 'active'
  order by starts_at desc
  limit 1;

  if found and v_race.ends_at > now() then
    return v_race;
  end if;

  -- Only cycle creation needs serialising; the common path above takes no lock.
  perform pg_advisory_xact_lock(918273645);

  select * into v_race
  from public.rorisk_races
  where status = 'active'
  order by starts_at desc
  limit 1;

  if found and v_race.ends_at > now() then
    return v_race;
  end if;

  for v_expired in
    select * from public.rorisk_races
    where status = 'active' and ends_at <= now()
    order by starts_at
    for update
  loop
    with ranked as (
      select user_uuid,
             row_number() over (order by points desc, updated_at asc, user_uuid) as place
      from public.rorisk_race_entries
      where race_id = v_expired.id and points > 0
    )
    update public.rorisk_race_entries as entry
    set prize = case ranked.place
        when 1 then floor(v_expired.prize_pool * 0.5)
        when 2 then floor(v_expired.prize_pool * 0.3)
        when 3 then floor(v_expired.prize_pool * 0.2)
        else 0
      end
    from ranked
    where entry.race_id = v_expired.id
      and entry.user_uuid = ranked.user_uuid
      and ranked.place <= 3;

    update public.rorisk_races set status = 'completed' where id = v_expired.id;
  end loop;

  insert into public.rorisk_races (starts_at, ends_at)
  values (now(), now() + interval '20160 minutes')
  returning * into v_race;

  return v_race;
end;
$$;

create or replace function public.apply_rorisk_wager(
  p_user_uuid uuid,
  p_currency text,
  p_wager bigint,
  p_payout bigint,
  p_rate integer
)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_xp bigint;
  v_points bigint;
  v_race public.rorisk_races%rowtype;
  v_currency text := case when p_currency = 'coins' then 'coins' else 'rocoins' end;
begin
  if p_user_uuid is null or coalesce(p_wager, 0) <= 0 then
    return;
  end if;
  if not exists (select 1 from public.rorisk_users where uuid = p_user_uuid) then
    return;
  end if;

  v_xp := greatest(1, floor(p_wager::numeric * greatest(0, coalesce(p_rate, 0))));
  v_points := greatest(1, floor((case when v_currency = 'coins' then p_wager * 5 else p_wager end)::numeric / 1000));

  if v_currency = 'coins' then
    update public.rorisk_users
    set total_bets = total_bets + 1,
        total_wagered_coins = total_wagered_coins + p_wager,
        total_won_coins = total_won_coins + greatest(0, coalesce(p_payout, 0)),
        xp = xp + v_xp,
        level = public.rorisk_level_for_xp(xp + v_xp)
    where uuid = p_user_uuid;
  else
    update public.rorisk_users
    set total_bets = total_bets + 1,
        total_wagered_rocoins = total_wagered_rocoins + p_wager,
        total_won_rocoins = total_won_rocoins + greatest(0, coalesce(p_payout, 0)),
        xp = xp + v_xp,
        level = public.rorisk_level_for_xp(xp + v_xp)
    where uuid = p_user_uuid;
  end if;

  v_race := public.ensure_rorisk_race();
  insert into public.rorisk_race_entries (race_id, user_uuid, points)
  values (v_race.id, p_user_uuid, v_points)
  on conflict (race_id, user_uuid) do update
  set points = public.rorisk_race_entries.points + excluded.points,
      updated_at = now();
end;
$$;

create or replace function public.rorisk_race_state(p_user_uuid uuid)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_race public.rorisk_races%rowtype;
  v_leaderboard jsonb;
  v_me jsonb;
  v_claimable bigint;
  v_won bigint;
begin
  v_race := public.ensure_rorisk_race();

  select coalesce(jsonb_agg(jsonb_build_object(
      'uuid', entry.user_uuid,
      'username', users.username,
      'avatar', users.avatar_headshot,
      'level', users.level,
      'rank', users.rank,
      'points', entry.points,
      'prize', entry.prize
    ) order by entry.points desc, entry.updated_at asc), '[]'::jsonb)
  into v_leaderboard
  from (
    select * from public.rorisk_race_entries
    where race_id = v_race.id
    order by points desc, updated_at asc
    limit 25
  ) as entry
  join public.rorisk_users as users on users.uuid = entry.user_uuid;

  if p_user_uuid is not null then
    select jsonb_build_object(
      'points', entry.points,
      'prize', entry.prize,
      'place', (
        select count(*) + 1
        from public.rorisk_race_entries as other
        where other.race_id = v_race.id
          and (other.points > entry.points or (other.points = entry.points and other.updated_at < entry.updated_at))
      )
    )
    into v_me
    from public.rorisk_race_entries as entry
    where entry.race_id = v_race.id and entry.user_uuid = p_user_uuid;
  end if;

  select count(*)
  into v_won
  from public.rorisk_race_entries as entry
  join public.rorisk_races as race on race.id = entry.race_id
  where entry.user_uuid = p_user_uuid
    and race.status = 'completed'
    and entry.prize > 0;

  select coalesce(sum(entry.prize), 0)
  into v_claimable
  from public.rorisk_race_entries as entry
  join public.rorisk_races as race on race.id = entry.race_id
  where entry.user_uuid = p_user_uuid
    and race.status = 'completed'
    and entry.prize > 0
    and entry.claimed = false;

  return jsonb_build_object(
    'race', jsonb_build_object(
      'id', v_race.id,
      'startsAt', v_race.starts_at,
      'endsAt', v_race.ends_at,
      'prizePool', v_race.prize_pool
    ),
    'serverTime', now(),
    'leaderboard', v_leaderboard,
    'me', v_me,
    'won', coalesce(v_won, 0),
    'claimable', v_claimable,
    'durationMinutes', 20160
  );
end;
$$;

create or replace function public.claim_rorisk_race_reward(p_user_uuid uuid)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_entry record;
  v_user public.rorisk_users%rowtype;
begin
  if p_user_uuid is null then
    raise exception 'Please sign in to perform this action.';
  end if;

  select entry.race_id, entry.prize
  into v_entry
  from public.rorisk_race_entries as entry
  join public.rorisk_races as race on race.id = entry.race_id
  where entry.user_uuid = p_user_uuid
    and race.status = 'completed'
    and entry.prize > 0
    and entry.claimed = false
  order by race.ends_at desc
  limit 1
  for update of entry;

  if not found then
    raise exception 'You have no race rewards to claim.';
  end if;

  update public.rorisk_race_entries
  set claimed = true, updated_at = now()
  where race_id = v_entry.race_id and user_uuid = p_user_uuid;

  update public.rorisk_users
  set coins = coins + v_entry.prize,
      total_rewards_coins = total_rewards_coins + v_entry.prize
  where uuid = p_user_uuid
  returning * into v_user;

  return jsonb_build_object('amount', v_entry.prize, 'user', to_jsonb(v_user));
end;
$$;

