-- Weekly race: 14 days = 20160 minutes, prizes split 50 / 30 / 20 from the pool.
create table if not exists public.rorisk_races (
  id bigint generated by default as identity primary key,
  uuid uuid not null unique default gen_random_uuid(),
  starts_at timestamptz not null,
  ends_at timestamptz not null,
  prize_pool bigint not null default 500000 check (prize_pool >= 0),
  status text not null default 'active' check (status in ('active', 'completed')),
  created_at timestamptz not null default now(),
  constraint rorisk_races_window check (ends_at > starts_at)
);

create index if not exists rorisk_races_status_idx on public.rorisk_races (status, ends_at desc);
create unique index if not exists rorisk_races_one_active_idx on public.rorisk_races (status) where status = 'active';

create table if not exists public.rorisk_race_entries (
  race_id bigint not null references public.rorisk_races(id) on delete cascade,
  user_uuid uuid not null references public.rorisk_users(uuid) on delete cascade,
  points bigint not null default 0 check (points >= 0),
  prize bigint not null default 0 check (prize >= 0),
  claimed boolean not null default false,
  updated_at timestamptz not null default now(),
  primary key (race_id, user_uuid)
);

create index if not exists rorisk_race_entries_rank_idx on public.rorisk_race_entries (race_id, points desc, updated_at asc);

alter table public.rorisk_races enable row level security;
alter table public.rorisk_race_entries enable row level security;
